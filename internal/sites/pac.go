package sites

import (
	"encoding/json"
	"fmt"
	"strings"
)

// PAC returns the proxy auto-config script for Safari / macOS. Everything
// goes through the proxy at addr, except local names, IP addresses and the
// never-decrypt list, which connect directly. If the proxy isn't running,
// browsers fall back to DIRECT, so websites keep working (ad domains stay
// blocked by shoo's DNS).
func PAC(addr string, l *List) string {
	var b strings.Builder
	b.WriteString("// Generated by shoo.\n")
	fmt.Fprintf(&b, "var SKIP = %s;\n", jsSet(l.pacSkip()))
	fmt.Fprintf(&b, `
function inSet(set, host) {
  for (;;) {
    if (Object.prototype.hasOwnProperty.call(set, host)) return true;
    var i = host.indexOf(".");
    if (i < 0) return false;
    host = host.substring(i + 1);
  }
}

function FindProxyForURL(url, host) {
  host = host.toLowerCase();
  if (isPlainHostName(host) || host.indexOf(":") >= 0 ||
      /^[0-9.]+$/.test(host) ||
      dnsDomainIs(host, ".local") || dnsDomainIs(host, ".localhost")) {
    return "DIRECT";
  }
  if (inSet(SKIP, host)) return "DIRECT";
  return "PROXY %[1]s; DIRECT";
}
`, addr)
	return b.String()
}

// jsSet writes {"a.com":1,"b.com":1,...}, one entry per line to keep it readable.
func jsSet(items []string) string {
	if len(items) == 0 {
		return "{}"
	}
	var b strings.Builder
	b.WriteString("{\n")
	for i, d := range items {
		k, _ := json.Marshal(d)
		b.Write(k)
		b.WriteString(":1")
		if i < len(items)-1 {
			b.WriteByte(',')
		}
		b.WriteByte('\n')
	}
	b.WriteString("}")
	return b.String()
}
