package sites

import (
	"encoding/json"
	"fmt"
	"strings"

	"ytblock/internal/certs"
)

// PAC returns the proxy auto-config script for Safari / macOS:
//
//  1. YouTube (certs.AllowedDomains) → the YouTube proxy, with DIRECT
//     fallback. This is the same routing the YouTube-only PAC uses.
//  2. Other YouTube domains (video stream, images) and allowed domains → DIRECT.
//  3. Blocked ad domains → the proxy, which refuses them. No DIRECT fallback,
//     so ads stay blocked even if the proxy isn't running.
//  4. Everything else → DIRECT.
func PAC(addr string, l *List) string {
	var b strings.Builder
	b.WriteString("// Generated by shoo.\n")
	fmt.Fprintf(&b, "var YT = %s;\n", jsArray(certs.AllowedDomains))
	fmt.Fprintf(&b, "var KEEP = %s;\n", jsSet(append(l.pacProtected(), l.pacAllowed()...)))
	fmt.Fprintf(&b, "var BLOCK = %s;\n", jsSet(l.pacBlocked()))
	fmt.Fprintf(&b, `
function inSet(set, host) {
  for (;;) {
    if (Object.prototype.hasOwnProperty.call(set, host)) return true;
    var i = host.indexOf(".");
    if (i < 0) return false;
    host = host.substring(i + 1);
  }
}

function FindProxyForURL(url, host) {
  host = host.toLowerCase();
  for (var i = 0; i < YT.length; i++) {
    if (host == YT[i] || dnsDomainIs(host, "." + YT[i])) return "PROXY %[1]s; DIRECT";
  }
  if (inSet(KEEP, host)) return "DIRECT";
  if (inSet(BLOCK, host)) return "PROXY %[1]s";
  return "DIRECT";
}
`, addr)
	return b.String()
}

func jsArray(items []string) string {
	j, _ := json.Marshal(items)
	return string(j)
}

// jsSet writes {"a.com":1,"b.com":1,...}, one entry per line to keep it readable.
func jsSet(items []string) string {
	if len(items) == 0 {
		return "{}"
	}
	var b strings.Builder
	b.WriteString("{\n")
	for i, d := range items {
		k, _ := json.Marshal(d)
		b.Write(k)
		b.WriteString(":1")
		if i < len(items)-1 {
			b.WriteByte(',')
		}
		b.WriteByte('\n')
	}
	b.WriteString("}")
	return b.String()
}
